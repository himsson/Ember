let LANG = 'en';
function setLang(code) {
  LANG = LANGS[code] ? code : 'en';
  document.documentElement.lang = LANG;
}
function t(text, ...vars) {
  text = String(text == null ? '' : text);
  const i = LANG_INDEX[LANG];
  let out = text;
  if (i != null) {
    const row = STRINGS[text];
    const cut = text.indexOf(': ');
    if (row) out = row[i] || text;
    else if (cut > 0 && STRINGS[text.slice(0, cut)]) out = STRINGS[text.slice(0, cut)][i] + text.slice(cut);
  }
  return vars.length ? out.replace(/\{(\d)\}/g, (m, n) => (vars[n] == null ? m : vars[n])) : out;
}
