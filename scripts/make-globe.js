const fs = require('fs');
const path = require('path');

const topo = JSON.parse(fs.readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8'));
const LANG_COUNTRY = {
  'United Kingdom': 1,
  Russia: 2,
  Germany: 3,
  China: 4,
  France: 5,
  Italy: 6,
  Spain: 7,
  'United States of America': 8,
};

const { scale, translate } = topo.transform;
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});
const ring = (ids) => ids.flatMap((i) => (i >= 0 ? arcs[i] : arcs[~i].slice().reverse()));
const polygons = [];
for (const g of topo.objects.countries.geometries) {
  const code = LANG_COUNTRY[g.properties.name] || 0;
  const polys = g.type === 'Polygon' ? [g.arcs] : g.arcs;
  for (const p of polys) {
    let rings = p.map(ring);
    let lons = rings[0].map((q) => q[0]);
    // Fiji straddles the antimeridian; untreated, its ring reads as a band around the planet.
    const wraps = Math.max(...lons) - Math.min(...lons) > 270;
    if (wraps) {
      rings = rings.map((r) => r.map(([x, y]) => [x < 0 ? x + 360 : x, y]));
      lons = rings[0].map((q) => q[0]);
    }
    const lats = rings[0].map((q) => q[1]);
    polygons.push({
      code,
      wraps,
      rings,
      box: [Math.min(...lons), Math.min(...lats), Math.max(...lons), Math.max(...lats)],
    });
  }
}

function inRing(lon, lat, r) {
  let inside = false;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const [xi, yi] = r[i];
    const [xj, yj] = r[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function countryAt(lon0, lat) {
  for (const p of polygons) {
    const lon = p.wraps && lon0 < 0 ? lon0 + 360 : lon0;
    if (lon < p.box[0] || lon > p.box[2] || lat < p.box[1] || lat > p.box[3]) continue;
    if (inRing(lon, lat, p.rings[0]) && !p.rings.slice(1).some((h) => inRing(lon, lat, h))) return p.code;
  }
  return -1;
}

const STEP = 1.8;
const dots = [];
for (let lat = -58; lat <= 84; lat += STEP) {
  const n = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / STEP));
  for (let k = 0; k < n; k++) {
    const lon = -180 + (360 * (k + 0.5)) / n;
    const code = countryAt(lon, lat);
    if (code >= 0) dots.push(Math.round(lat * 10), Math.round(lon * 10), code);
  }
}
fs.writeFileSync(
  path.join(__dirname, '..', 'ui', 'globe-data.js'),
  `// Generated by scripts/make-globe.js. Triples: latitude*10, longitude*10, language country (0 = none).\nconst GLOBE_DOTS = new Int16Array([${dots.join(',')}]);\n`,
);
console.log(
  'dots:',
  dots.length / 3,
  'per country:',
  [1, 2, 3, 4, 5, 6, 7, 8].map((c) => dots.filter((v, i) => i % 3 === 2 && v === c).length).join(' '),
);
